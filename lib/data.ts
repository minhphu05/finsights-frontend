export type Tone = 'ceil' | 'up' | 'ref' | 'down' | 'floor';
const limits: Record<string, number> = { HOSE: 7, HNX: 10, UPCOM: 15 };
export const priceTone = (s: Stock): Tone => {
  const limit = limits[s.exchange] ?? 7;
  return s.change >= limit - 0.1
    ? 'ceil'
    : s.change <= -(limit - 0.1)
      ? 'floor'
      : s.change > 0
        ? 'up'
        : s.change < 0
          ? 'down'
          : 'ref';
};
// Bước giá: HOSE 10 / 50 / 100 đồng theo vùng giá; HNX và UPCOM 100 đồng.
const tick = (exchange: string, price: number) =>
  exchange !== 'HOSE' ? 100 : price < 10000 ? 10 : price < 50000 ? 50 : 100;
export const priceBands = (s: Stock) => {
  const raw = s.price / (1 + s.change / 100),
    ref = Math.round(raw / tick(s.exchange, raw)) * tick(s.exchange, raw),
    limit = (limits[s.exchange] ?? 7) / 100;
  const up = ref * (1 + limit),
    down = ref * (1 - limit);
  return {
    ref,
    ceil: Math.floor(up / tick(s.exchange, up)) * tick(s.exchange, up),
    floor: Math.ceil(down / tick(s.exchange, down)) * tick(s.exchange, down),
  };
};
